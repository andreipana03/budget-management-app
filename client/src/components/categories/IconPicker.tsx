export default function IconPicker({ value, onChange }: IconPickerProps) {
  const [activeCategory, setActiveCategory] = useState(0);

  const currentEmojis = EMOJI_CATEGORIES[activeCategory].emojis;

  return (
    <div className="border border-gray-200 dark:border-gray-600 rounded-lg overflow-hidden">
      {/* Category tabs */}
      <div className="flex overflow-x-auto bg-gray-100 dark:bg-gray-700/60 border-b border-gray-200 dark:border-gray-600">
        {EMOJI_CATEGORIES.map((cat, i) => (
          <button
            key={i}
            type="button"
            onClick={() => setActiveCategory(i)}
            title={cat.label}
            className={`flex-shrink-0 px-2.5 py-1.5 text-lg transition-colors ${
              activeCategory === i
                ? 'bg-white dark:bg-gray-800 border-b-2 border-primary-500'
                : 'hover:bg-gray-200 dark:hover:bg-gray-600'
            }`}
          >
            {cat.icon}
          </button>
        ))}
      </div>

      {/* Category label */}
      <div className="px-2 py-1 text-xs font-medium text-gray-500 dark:text-gray-400 bg-gray-50 dark:bg-gray-700/30 border-b border-gray-200 dark:border-gray-600">
        {EMOJI_CATEGORIES[activeCategory].label}
      </div>

      {/* Emoji grid */}
      <div className="grid grid-cols-10 gap-0.5 max-h-52 overflow-y-auto p-1.5 bg-white dark:bg-gray-800">
        {currentEmojis.map((emoji, i) => (
          <button
            key={`${activeCategory}-${i}`}
            type="button"
            onClick={() => onChange(emoji)}
            className={`w-8 h-8 flex items-center justify-center rounded-md text-lg transition-colors hover:bg-gray-100 dark:hover:bg-gray-700 ${
              value === emoji ? 'bg-primary-100 dark:bg-primary-900/40 ring-2 ring-primary-500' : ''
            }`}
          >
            {emoji}
          </button>
        ))}
      </div>

      {/* Clear */}
      {value && (
        <div className="px-2 py-1 bg-gray-50 dark:bg-gray-700/30 border-t border-gray-200 dark:border-gray-600">
          <button
            type="button"
            onClick={() => onChange('')}
            className="text-xs text-gray-400 hover:text-gray-600 dark:hover:text-gray-300"
          >
            Clear icon
          </button>
        </div>
      )}
    </div>
  );
}
